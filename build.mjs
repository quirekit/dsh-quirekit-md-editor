/**
 * Builds lib/client.js, the single classic script DSH serves for a plugin, and lib/frame/, the
 * editor document the host half serves. DSH answers `require` only for its platform modules, so
 * everything else is inlined and the shell's CSS travels inside its script.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { bundleOptions, usesLocalQuireKit } from './scripts/bundle-options.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const scratch = join(root, 'build', 'client');
const body = join(scratch, 'client.body.js');
const output = join(root, 'lib', 'client.js');
const frameDirectory = join(root, 'lib', 'frame');
rmSync(scratch, { recursive: true, force: true });
rmSync(frameDirectory, { recursive: true, force: true });
mkdirSync(frameDirectory, { recursive: true });

// The editor runs in its own document, so the host page's stylesheets never restyle it.
const frame = await build({
  ...bundleOptions,
  entryPoints: ['src/client/frame-entry.js'],
  outfile: join(frameDirectory, 'editor.js'),
  format: 'iife',
  metafile: true,
});
// The frame is as wide as the sidebar, so the phone breakpoint would otherwise apply on a desktop window.
const frameCss = join(frameDirectory, 'editor.css');
writeFileSync(frameCss, readFileSync(frameCss, 'utf8').replaceAll('(max-width:767px)', '(max-width:0px)'));
writeFileSync(join(frameDirectory, 'index.html'), '<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="editor.css"><script src="editor.js"></script></head><body><div id="root" class="qk-dsh-editor"></div></body></html>\n');
const frameBytes = readFileSync(join(frameDirectory, 'editor.js'));
const frameVersion = createHash('sha256').update(frameBytes).update(readFileSync(join(frameDirectory, 'editor.css'))).digest('hex').slice(0, 16);

const result = await build({
  ...bundleOptions,
  entryPoints: ['src/client/index.js'],
  outfile: body,
  format: 'cjs',
  metafile: true,
  define: { ...bundleOptions.define, __FRAME_VERSION__: JSON.stringify(frameVersion) },
});

const script = readFileSync(body, 'utf8');
const css = readFileSync(body.replace(/\.js$/, '.css'), 'utf8');
const wrapped = `// Generated by build.mjs.
window.__ModuleLoader__.load({id:${JSON.stringify(pkg.name)},factory:(require)=>{
var style=document.createElement('style');style.dataset.plugin=${JSON.stringify(pkg.name)};style.textContent=${JSON.stringify(css)};document.head.appendChild(style);
var module={exports:{}};var exports=module.exports;
${script}
return module.exports;}});
`;
writeFileSync(output, wrapped);
writeFileSync(join(scratch, 'meta.json'), JSON.stringify(result.metafile));

/** Everything inlined into the script needs attribution, so the notice follows the real bundle. */
const packages = new Map();
for (const file of Object.keys({ ...frame.metafile.inputs, ...result.metafile.inputs })) {
  const match = file.match(/^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\/(?!.*node_modules\/)/u);
  if (match !== null) packages.set(match[1], match[2]);
}
const rows = [...packages].map(([directory, name]) => {
  const manifest = JSON.parse(readFileSync(join(root, directory, 'package.json'), 'utf8'));
  const license = typeof manifest.license === 'string' ? manifest.license : manifest.license?.type ?? 'See package';
  return `| ${name} | ${manifest.version} | ${license} |`;
}).sort((left, right) => left.localeCompare(right));
// A local build's contents are not what gets published, so it leaves the notice alone.
if (!usesLocalQuireKit) writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), `# Third-party notices

\`lib/\` includes the following packages. Each remains under its own license; see the package in the npm registry for the full text.

| Package | Version | License |
| --- | --- | --- |
${[...new Set(rows)].join('\n')}
`);

const size = text => `${(Buffer.byteLength(text) / 1048576).toFixed(2)} MB (gzip ${(gzipSync(text).length / 1048576).toFixed(2)} MB)`;
console.log(`client.js  ${size(wrapped)}`);
console.log(`editor.js  ${size(frameBytes)}`);
console.log(`  js  ${size(script)}`);
console.log(`  css ${size(css)}`);

const groups = new Map();
for (const [file, entry] of Object.entries(Object.values(frame.metafile.outputs).find(o => o.entryPoint)?.inputs ?? {})) {
  const match = file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)(?!.*node_modules\/)/);
  const key = match?.[1] ?? 'src';
  groups.set(key, (groups.get(key) ?? 0) + entry.bytesInOutput);
}
for (const [key, bytes] of [...groups].sort((a, b) => b[1] - a[1]).slice(0, 18)) {
  console.log(`  ${(bytes / 1024).toFixed(0).padStart(6)} KB  ${key}`);
}
